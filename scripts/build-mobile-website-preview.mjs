import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const destination = new URL('../mobile/assets/website_preview/renderer.html', import.meta.url);
const result = await build({
  absWorkingDir: fileURLToPath(new URL('..', import.meta.url)),
  entryPoints: ['web/src/websiteMobilePreviewHost.ts'],
  bundle: true,
  write: false,
  format: 'iife',
  target: ['chrome109', 'safari16'],
  minify: true,
  legalComments: 'none',
});
const script = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const html = `<!doctype html>
<!-- Generated by scripts/build-mobile-website-preview.mjs. -->
<html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline' blob:; style-src 'unsafe-inline'; frame-src about:; worker-src blob:; img-src data:; font-src data:; base-uri 'none'; form-action 'none'">
<meta name="referrer" content="no-referrer">
<style>
html,body{margin:0;height:100%;font:14px/1.5 system-ui,sans-serif;color:#232329;background:#fff}
body{display:flex;flex-direction:column;overflow:hidden}
#toolbar{display:flex;align-items:center;gap:10px;padding:4px 10px;border-bottom:1px solid #e4e4e7}
#toolbar button{font:inherit;min-height:44px;padding:4px 10px;border:0;border-radius:12px;background:#f4f4f5;color:inherit}
#toolbar span{overflow:hidden;text-overflow:ellipsis;white-space:nowrap}
#status{margin:12px}
iframe{border:0;min-height:0;width:100%;flex:1}
[hidden]{display:none!important}
</style></head><body>
<header id="toolbar" hidden><button type="button"></button><span></span></header>
<p id="status" role="status" hidden></p>
<iframe id="preview" sandbox="allow-scripts allow-pointer-lock" referrerpolicy="no-referrer" hidden></iframe>
<script>${script}</script>
</body></html>
`;
if (process.argv.includes('--check')) {
  if ((await readFile(destination, 'utf8')) !== html) {
    throw Error(
      'Rebuild the Flutter website preview asset with node scripts/build-mobile-website-preview.mjs.',
    );
  }
} else {
  await writeFile(destination, html);
}
