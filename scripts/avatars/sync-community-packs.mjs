import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../..', import.meta.url));
const check = process.argv.includes('--check');
const catalog = JSON.parse(await readFile(resolve(root, 'shared/avatar-packs/catalog.json'), 'utf8'));
const outputs = new Map();
const quoted = (value) => `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'").replaceAll('$', '\\$')}'`;
const escaped = (value) => value.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');
const themes = catalog.packs.flatMap((pack) => pack.themes.map((theme) => ({ ...theme, pack: pack.id })));
outputs.set('mobile/lib/core/community_avatar_catalog.g.dart', `// Generated by scripts/avatars/sync-community-packs.mjs. Do not edit.
const communityAvatarThemes = <String>[
${themes.map((theme) => `  ${quoted(theme.id)},`).join('\n')}
];
const communityAvatarGroups = <String, String>{
${themes.map((theme) => `  ${quoted(theme.id)}: ${quoted(theme.pack)},`).join('\n')}
};
const communityAvatarLabels = <String, Map<String, String>>{
${themes.map((theme) => `  ${quoted(theme.id)}: {'en': ${quoted(theme.label.en)}, 'zh': ${quoted(theme.label.zh)}},`).join('\n')}
};
`);
outputs.set('mobile/assets/avatars/packs/catalog.json', await readFile(resolve(root, 'shared/avatar-packs/catalog.json')));
for (const pack of catalog.packs) {
  for (const file of ['manifest.json', 'expressions.json']) {
    outputs.set(`mobile/assets/avatars/packs/${pack.id}/${file}`, await readFile(resolve(root, `shared/avatar-packs/${pack.id}/${file}`)));
  }
  const license = await readFile(resolve(root, `shared/avatar-packs/${pack.id}/LICENSE`), 'utf8');
  outputs.set(`mobile/assets/licenses/${pack.id}-LICENSE.txt`, license);
  outputs.set(`web/public/licenses/${pack.id}.html`, `<!doctype html>
<html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>${escaped(pack.name)} — license</title>
<style>body{max-width:64rem;margin:3rem auto;padding:0 1.5rem;font:16px/1.6 system-ui}pre{white-space:pre-wrap}</style>
<h1>${escaped(pack.name)}</h1><p>${escaped(pack.license)} · Community avatar adaptation</p>
<pre>${escaped(license)}</pre></html>
`);
}
let stale = 0;
for (const [path, content] of outputs) {
  const target = resolve(root, path);
  if (check) {
    const actual = await readFile(target).catch(() => null);
    if (!actual?.equals(Buffer.from(content))) {
      console.error(`Out of date: ${path}`);
      stale += 1;
    }
  } else {
    await mkdir(dirname(target), { recursive: true });
    await writeFile(target, content);
  }
}
console.log(`${outputs.size} community avatar outputs ${check ? 'checked' : 'updated'}; ${stale} mismatches.`);
process.exitCode = stale ? 1 : 0;
